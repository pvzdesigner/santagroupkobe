---@param Table any
---@return string
--- Function that selects the VIP rank with the highest weight from a given table.
function GetVIPRank(Table)
    local Result = { emote = "", group = "", weight = 0 }

    for Group, _ in pairs(Table) do
        if VIPRanks[Group] and VIPRanks[Group]["weight"] and type(VIPRanks[Group]["weight"]) == "number" then
            if VIPRanks[Group]["weight"] > Result["weight"] then
                Result = {
                    emote = VIPRanks[Group]["emote"] or "",
                    group = Group,
                    weight = VIPRanks[Group]["weight"]
                }
            end
        end
    end

    return Result
end

